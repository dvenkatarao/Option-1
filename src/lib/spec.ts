const verLabel: Record<Source["verification"], string> = {
  live: "VERIFIED LIVE (called, valid data returned)",
  docs: "VERIFIED IN OFFICIAL DOCS (key required, not called)",
  partial: "PARTIAL (reachable with caveat)",
  failed: "FAILED / RETIRED (do not use)",
};

function renderSource(s: Source): string {
  const lines = [
    `#### ${s.name}`,
    `- **Provider:** ${s.provider}`,
    `- **Base URL:** \`${s.baseUrl}\``,
    `- **Docs:** ${s.docsUrl}`,
    `- **Auth:** ${s.auth}${s.envVar ? ` (env: \`${s.envVar}\`)` : ""}`,
    `- **Free limits:** ${s.freeLimits}`,
    `- **Verification (${VERIFIED_ON}):** ${verLabel[s.verification]} - ${s.testedNote}`,
  ];
  if (s.provides.length) lines.push(`- **Provides:**`, ...s.provides.map((p) => `  - ${p}`));
  if (s.endpoints.length) lines.push(`- **Endpoints:**`, ...s.endpoints.map((p) => `  - \`${p}\``));
  if (s.caveats.length) lines.push(`- **Caveats:**`, ...s.caveats.map((p) => `  - ${p}`));
  return lines.join("\n");
}

